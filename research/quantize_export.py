"""
CardioSentinel Edge - Model Quantization & C Header Exporter
TECHgium Challenge 26 Research Prototype

Exports fused Conv1D+BN and Dense layer weights to an embedded C header file
(tinycnn_weights.h) for zero-dependency execution on ESP32-S3 internal SRAM.
"""

import os
import json
import numpy as np
import torch
from typing import Dict, Any

from research.models_tiny import CardioSentinelTinyCNN, fuse_conv_bn_weights


def export_fused_c_header(
    model: CardioSentinelTinyCNN,
    output_header_path: str = "firmware/esp32s3/models/tinycnn_weights.h"
) -> Dict[str, Any]:
    """
    Fuses Conv1D + BatchNorm layers and generates an optimized C header file.
    """
    os.makedirs(os.path.dirname(output_header_path), exist_ok=True)
    model.eval()

    # Fuse Conv + BN for all 3 blocks
    w1, b1 = fuse_conv_bn_weights(model.conv1, model.bn1)
    w2, b2 = fuse_conv_bn_weights(model.conv2, model.bn2)
    w3, b3 = fuse_conv_bn_weights(model.conv3, model.bn3)

    w_fc1 = model.fc1.weight.detach().cpu().numpy().astype(np.float32)
    b_fc1 = model.fc1.bias.detach().cpu().numpy().astype(np.float32)

    w_fc2 = model.fc2.weight.detach().cpu().numpy().astype(np.float32)
    b_fc2 = model.fc2.bias.detach().cpu().numpy().astype(np.float32)

    def array_to_c_string(arr: np.ndarray, name: str, dtype: str = "float") -> str:
        flat = arr.flatten()
        lines = [f"static const {dtype} {name}[{len(flat)}] = {{"]
        chunk_size = 8
        for i in range(0, len(flat), chunk_size):
            chunk = flat[i:i + chunk_size]
            vals = ", ".join([f"{v:.6f}f" if dtype == "float" else str(v) for v in chunk])
            comma = "," if i + chunk_size < len(flat) else ""
            lines.append(f"    {vals}{comma}")
        lines.append("};\n")
        return "\n".join(lines)

    header_content = [
        "/**",
        " * CardioSentinel Edge - TinyCNN Weights Header",
        " * Auto-generated by research/quantize_export.py",
        " * Target: ESP32-S3 Xtensa LX7 (Internal Zero-Wait SRAM)",
        " */",
        "",
        "#ifndef TINYCNN_WEIGHTS_H",
        "#define TINYCNN_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
        "// Architecture Dimensions",
        "#define INPUT_LENGTH          2500",
        "#define CONV1_OUT_CHANNELS    16",
        "#define CONV1_KERNEL_SIZE     7",
        "#define CONV1_STRIDE          2",
        "#define CONV1_PAD             3",
        "",
        "#define CONV2_OUT_CHANNELS    32",
        "#define CONV2_KERNEL_SIZE     5",
        "#define CONV2_STRIDE          2",
        "#define CONV2_PAD             2",
        "",
        "#define CONV3_OUT_CHANNELS    48",
        "#define CONV3_KERNEL_SIZE     3",
        "#define CONV3_STRIDE          2",
        "#define CONV3_PAD             1",
        "",
        "#define FC1_IN_FEATURES       48",
        "#define FC1_OUT_FEATURES      24",
        "#define NUM_CLASSES           3",
        "",
        "// Temperature Scaling & Decision Thresholds",
        "#define CALIBRATED_TEMPERATURE   1.1500f",
        "#define ACCEPT_CONF_THRESH       0.6800f",
        "#define MARGIN_AMBIGUITY_THRESH  0.1500f",
        "",
        "// Fused Weights & Biases",
        array_to_c_string(w1, "TINYCNN_CONV1_W"),
        array_to_c_string(b1, "TINYCNN_CONV1_B"),
        array_to_c_string(w2, "TINYCNN_CONV2_W"),
        array_to_c_string(b2, "TINYCNN_CONV2_B"),
        array_to_c_string(w3, "TINYCNN_CONV3_W"),
        array_to_c_string(b3, "TINYCNN_CONV3_B"),
        array_to_c_string(w_fc1, "TINYCNN_FC1_W"),
        array_to_c_string(b_fc1, "TINYCNN_FC1_B"),
        array_to_c_string(w_fc2, "TINYCNN_FC2_W"),
        array_to_c_string(b_fc2, "TINYCNN_FC2_B"),
        "",
        "#endif // TINYCNN_WEIGHTS_H",
        ""
    ]

    full_text = "\n".join(header_content)
    with open(output_header_path, "w") as f:
        f.write(full_text)

    total_params = len(w1.flatten()) + len(b1) + len(w2.flatten()) + len(b2) + \
                   len(w3.flatten()) + len(b3) + len(w_fc1.flatten()) + len(b_fc1) + \
                   len(w_fc2.flatten()) + len(b_fc2)
    byte_size = total_params * 4

    print(f"[EXPORT] Successfully generated C header: {output_header_path}")
    print(f"[EXPORT] Total Fused Parameters: {total_params} (~{byte_size / 1024:.2f} KB)")

    return {
        "header_path": output_header_path,
        "total_params": total_params,
        "size_kb": round(byte_size / 1024, 2),
        "fused_arrays": {
            "w1": w1, "b1": b1,
            "w2": w2, "b2": b2,
            "w3": w3, "b3": b3,
            "w_fc1": w_fc1, "b_fc1": b_fc1,
            "w_fc2": w_fc2, "b_fc2": b_fc2
        }
    }
